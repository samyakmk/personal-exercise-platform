import { expect, test } from './signed-in';

test('a fresh profile can start, resume, and save a suggested session without choosing exercises', async ({ page }) => {
  await page.clock.setFixedTime(new Date(2026, 10, 15, 12));
  await page.goto('/');
  await page.getByRole('button', { name: 'Skip for now' }).click();
  await expect(page.getByRole('button', { name: 'Set up training' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Start suggested session' }).click();
  let guide = page.getByRole('dialog', { name: 'Balanced strength' });
  await expect(guide.getByRole('textbox', { name: 'Reps · Bodyweight Squat' })).toHaveValue('6');
  await guide.getByRole('button', { name: 'Record set' }).click();
  await guide.getByRole('button', { name: 'Add exercise notes' }).click();
  await guide.getByRole('textbox', { name: 'Exercise notes · Bodyweight Squat' }).fill('Used a slow descent.');
  await guide.getByRole('button', { name: 'Pause session' }).click();
  await page.reload();
  await page.getByRole('button', { name: 'Resume session' }).click();
  guide = page.getByRole('dialog', { name: 'Balanced strength' });
  await guide.getByRole('button', { name: 'Edit exercise notes' }).click();
  await expect(guide.getByRole('textbox', { name: 'Exercise notes · Bodyweight Squat' })).toHaveValue('Used a slow descent.');
  await guide.getByRole('button', { name: 'Finish session' }).click();
  await guide.getByRole('combobox', { name: 'Perceived effort (optional)' }).selectOption('8');
  await guide.getByRole('textbox', { name: 'Session notes' }).fill('Keep it lighter next time.');
  await guide.getByRole('button', { name: 'Save session', exact: true }).click();
  await expect(page.getByText('Liftmorrow suggestion', { exact: true })).toBeVisible();
  await expect(page.getByText('Perceived effort · 8/10')).toBeVisible();
  await expect(page.getByText('Used a slow descent.')).toBeVisible();
  await expect(page.getByText('Keep it lighter next time.')).toBeVisible();
  await page.getByRole('link', { name: 'Overview', exact: true }).click();
  await expect(page.getByText('You already logged training today.')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Start suggested session' })).toHaveCount(0);
});

test('a narrow screen can keep trainer preferences and log check-ins with or without a reply', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.clock.setFixedTime(new Date(2026, 10, 15, 12));
  await page.goto('/');
  await page.getByRole('button', { name: 'Set up training' }).click();
  await page.getByRole('textbox', { name: 'Training goal' }).fill('Stronger upper body');
  await page.getByRole('textbox', { name: 'What has your trainer asked you to work on between sessions?' }).fill('Keep a controlled pace.');
  await page.getByRole('button', { name: 'Upper body', exact: true }).click();
  await page.getByRole('button', { name: 'Save profile', exact: true }).click();
  await expect(page.getByText('Profile details saved.')).toBeVisible();
  await page.getByRole('button', { name: 'Show profile history' }).click();
  const revisions = page.getByRole('list', { name: 'Saved training profile revisions' });
  await expect(revisions.getByText('Keep a controlled pace.', { exact: true })).toBeVisible();
  await page.goto('/');
  await expect(page.getByText('Includes work for your saved muscle priorities.')).toBeVisible();
  await page.getByRole('button', { name: 'Training check-in', exact: true }).focus();
  await page.keyboard.press('Enter');
  const checkIn = page.getByRole('dialog', { name: 'Training check-in' });
  const input = checkIn.getByRole('textbox');
  await input.fill('A quieter day today.');
  await checkIn.getByRole('button', { name: 'Rest today', exact: true }).click();
  await checkIn.getByRole('button', { name: 'Save without reply' }).click();
  await expect(checkIn.getByText('Check-in saved privately.')).toBeVisible();
  await expect(checkIn.getByText('Liftmorrow', { exact: true })).toHaveCount(0);
  await checkIn.getByRole('button', { name: 'Close dialog' }).click();
  await expect(page.getByText('You asked to rest today.')).toBeVisible();
  await page.reload();
  await expect(page.getByText('You asked to rest today.')).toBeVisible();
  await page.getByRole('button', { name: 'Training check-in', exact: true }).click();
  await checkIn.getByRole('button', { name: 'Clear adjustment', exact: true }).click();
  await input.fill('What is my plan?');
  await checkIn.getByRole('button', { name: 'Save and get a reply' }).click();
  await expect(checkIn.getByText(/Your check-in adjustment for today is cleared/)).toBeVisible();
  await checkIn.getByRole('button', { name: 'Close dialog' }).click();
  await expect(page.getByRole('button', { name: 'Start suggested session' })).toBeVisible();
});

test('logging yesterday’s trainer session makes today lighter and keeps the handoff visible', async ({ page }) => {
  await page.clock.setFixedTime(new Date(2026, 10, 15, 12));
  await page.goto('/');
  await page.getByRole('button', { name: 'Log a session' }).click();
  const editor = page.getByRole('dialog', { name: 'New session' });
  await editor.getByRole('textbox', { name: 'Session name' }).fill('Leg day with my trainer');
  await editor.getByLabel('Date', { exact: true }).fill('2026-11-14');
  await editor.getByRole('combobox', { name: 'Who planned this session?' }).selectOption('trainer');
  await editor.getByRole('combobox', { name: 'Perceived effort (optional)' }).selectOption('8');
  await editor.getByRole('textbox', { name: 'Session notes' }).fill('Keep the descent controlled.');
  await editor.getByRole('button', { name: 'Save and continue' }).click();
  await page.getByRole('dialog', { name: 'Session exercises' }).getByRole('button', { name: 'Close dialog' }).click();
  await expect(page.getByText('Trainer session', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Overview', exact: true }).click();
  await expect(page.getByText('A lighter strength session')).toBeVisible();
  await expect(page.getByText('Yesterday’s trainer session keeps today shorter.')).toBeVisible();
  await expect(page.getByText('Keep the descent controlled.')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Start suggested session' })).toBeVisible();
});
